/**
 * multi_dim_array.c
 * 覆盖: 2D/3D 数组访问
 *
 * arr[2][3][4]:
 *   arr[0][0][0]=1, arr[0][1][0]=2, arr[1][0][0]=3, arr[1][1][1]=4, arr[1][2][3]=5
 *   sum = 1+2+3+4+5 = 15
 * 退出码: 15
 */
int main(void) {
    int arr[2][3][4] = {0};
    arr[0][0][0] = 1;
    arr[0][1][0] = 2;
    arr[1][0][0] = 3;
    arr[1][1][1] = 4;
    arr[1][2][3] = 5;

    int sum = 0;
    sum += arr[0][0][0];  // 1
    sum += arr[0][1][0];  // 2
    sum += arr[1][0][0];  // 3
    sum += arr[1][1][1];  // 4
    sum += arr[1][2][3];  // 5
    return sum;  // 15
}
